import { phone, BASE, finish } from './lib.mjs';
const F = new URL('./files/', import.meta.url).pathname;
const R = []; const check = (n, c, d = '') => R.push([c ? 'PASS' : 'FAIL', n, d]);
const { browser, ctx, page, errors } = await phone();
await page.goto(BASE + '#comps', { waitUntil: 'load' });
await page.waitForFunction(() => navigator.serviceWorker && navigator.serviceWorker.controller || false, null, { timeout: 15000 }).catch(() => {});
const ctrl1 = await page.evaluate(() => !!navigator.serviceWorker.controller);
console.log('controlled after first load:', ctrl1);
let ctrl = ctrl1;
if (!ctrl1) { await page.reload({ waitUntil: 'load' }); ctrl = await page.evaluate(() => !!navigator.serviceWorker.controller); console.log('controlled after reload:', ctrl); }
check('the service worker controls the page', ctrl);
const keys = await page.evaluate(async () => { const k = await caches.keys(); const c = await caches.open(k[0]); return [k, (await c.keys()).length]; });
console.log('caches', JSON.stringify(keys));
check('the app cache is named for this version and filled', /^zlatura-\d/.test(keys[0][0] || '') && keys[1] > 0, JSON.stringify(keys));
console.log('toast on first visit', await page.locator('.toast').allTextContents());
await ctx.setOffline(true);
await page.reload({ waitUntil: 'load' });
await page.waitForTimeout(800);
const shownOff = await page.locator('#shell').isVisible(); const loadErr = await page.locator('#load-error').isVisible();
console.log('offline: app shown', shownOff, 'load-error', loadErr);
check('offline: the app opens with no load error', shownOff && !loadErr);
await page.click('.tab[data-view="deal"] >> visible=true');
await page.setInputFiles('#om-file', F + 'om-netlease.pdf');
await page.waitForSelector('#deal-tiles .tile', { timeout: 20000 }).catch(() => {});
const offTiles = await page.locator('#deal-tiles .tile').count();
console.log('offline OM read tiles:', offTiles, await page.locator('.toast').allTextContents());
check('offline: an OM is read', offTiles > 0, String(offTiles));
const [dl] = await Promise.all([page.waitForEvent('download', { timeout: 20000 }).catch(() => null), page.click('#deal-root .view-head .btn-primary')]);
console.log('offline excel download:', dl ? dl.suggestedFilename() : 'NONE', await page.locator('.toast').allTextContents());
check('offline: the deal workbook downloads', !!dl && /\.xlsx$/.test(dl.suggestedFilename()), dl ? dl.suggestedFilename() : 'none');
await ctx.setOffline(false);
const errs = errors.filter((e) => !/ERR_INTERNET_DISCONNECTED/.test(e));
check('no console errors other than being offline', errs.length === 0, errs.join(' / '));
for (const [s, n, d] of R) console.log(s, '|', n, d ? `| ${d}` : '');
finish(R, 'errors', errs);
await browser.close();
